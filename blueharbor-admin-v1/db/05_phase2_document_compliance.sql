CREATE TABLE IF NOT EXISTS compliance_rule_sets (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  country TEXT NOT NULL,
  product_category TEXT NOT NULL DEFAULT '*',
  requirement_code TEXT NOT NULL,
  document_name TEXT NOT NULL,
  issuer TEXT NOT NULL,
  buyer_owned INTEGER NOT NULL DEFAULT 0 CHECK (buyer_owned IN (0,1)),
  blocking INTEGER NOT NULL DEFAULT 1 CHECK (blocking IN (0,1)),
  lead_days INTEGER NOT NULL DEFAULT 0 CHECK (lead_days BETWEEN 0 AND 365),
  source_url TEXT NOT NULL,
  reviewed_on TEXT NOT NULL,
  active INTEGER NOT NULL DEFAULT 1 CHECK (active IN (0,1)),
  version INTEGER NOT NULL DEFAULT 1,
  updated TEXT NOT NULL DEFAULT '',
  UNIQUE(country,product_category,requirement_code)
);

CREATE TABLE IF NOT EXISTS exporter_credentials (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  authority TEXT NOT NULL,
  number TEXT NOT NULL,
  scope TEXT NOT NULL,
  issued TEXT NOT NULL DEFAULT '',
  expires TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'ACTIVE',
  notes TEXT NOT NULL DEFAULT '',
  updated TEXT NOT NULL DEFAULT '',
  UNIQUE(name,number)
);

CREATE TABLE IF NOT EXISTS order_document_requirements (
  order_id TEXT NOT NULL REFERENCES orders(id),
  requirement_code TEXT NOT NULL,
  document_name TEXT NOT NULL,
  owner TEXT NOT NULL CHECK (owner IN ('BUYER','EXPORTER')),
  blocking INTEGER NOT NULL DEFAULT 1 CHECK (blocking IN (0,1)),
  status TEXT NOT NULL DEFAULT 'WAITING',
  due_date TEXT NOT NULL DEFAULT '',
  source_rule_id BIGINT REFERENCES compliance_rule_sets(id),
  note TEXT NOT NULL DEFAULT '',
  updated TEXT NOT NULL DEFAULT '',
  PRIMARY KEY(order_id,requirement_code)
);

