ALTER TABLE trade_documents ADD COLUMN IF NOT EXISTS issue_date TEXT NOT NULL DEFAULT '';
ALTER TABLE trade_documents ADD COLUMN IF NOT EXISTS expiry_date TEXT NOT NULL DEFAULT '';

