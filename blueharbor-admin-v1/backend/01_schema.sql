CREATE TABLE shipment_orders(
    shipment_id TEXT REFERENCES transport_shipments(id),
    order_id TEXT REFERENCES orders(id),
    created TEXT NOT NULL,
    PRIMARY KEY(shipment_id, order_id),
    UNIQUE(order_id)
);

CREATE TABLE transport_legs(
